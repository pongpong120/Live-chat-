const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8');
const app = fs.readFileSync(path.join(root, 'public/app.js'), 'utf8');
const server = fs.readFileSync(path.join(root, 'server.js'), 'utf8');
assert.match(html, /id="modal-daily-task"/, 'premium Daily Task popup exists');
assert.match(html, /id="btn-room-daily-task"/, 'room quickbar contains Daily Task shortcut');
assert.match(html, /id="daily-task-popup-schedule"/, 'popup shows the seven-day reward schedule');
assert.match(server, /DAILY_DIAMOND_REWARDS = \[60000, 60000, 120000, 120000, 120000, 120000, 380000\]/, 'seven-day reward amounts are server-authoritative');
assert.match(html, /icon-diamond-premium\.png/, 'daily reward uses the app diamond asset');
assert.match(html, /Sign in securely with your Google account\./, 'login copy advertises Google sign-in only');
assert.doesNotMatch(html, /btn-facebook-login|Continue with Facebook/, 'Facebook login control is removed');
assert.doesNotMatch(app, /signInWithFacebook|btn-facebook-login/, 'Facebook login handler is removed from the client');
assert.match(server, /signInProvider === \"facebook\.com\"/, 'server rejects Facebook sign-in tokens');
const rocket = fs.readFileSync(path.join(root, 'public/games/rocket-crash.html'), 'utf8');
assert.match(html, /rocket-game-fullscreen-frame/, 'Rocket Crash modal uses full-screen frame');
assert.match(html, /requestFullscreen/, 'Rocket Crash attempts native browser full-screen');
assert.match(rocket, /app-diamond-icon.*icon-diamond-premium\.png|icon-diamond-premium\.png.*app-diamond-icon/, 'Rocket Crash uses the app diamond asset');
assert.match(rocket, /max-width:none/, 'Rocket Crash layout can use full viewport width');
assert.match(server, /app\.get\("\/api\/daily-reward\/state", userAuth\.requireUserAuth/, 'reward state requires authenticated user');
assert.match(server, /app\.post\("\/api\/daily-reward\/claim", userAuth\.requireUserAuth/, 'claim endpoint requires authenticated user');
assert.match(server, /DAILY_DIAMOND_COOLDOWN_MS = 12 \* 60 \* 60 \* 1000/, 'server enforces a 12-hour claim cooldown');
assert.match(server, /Reward already collected/, 'server blocks claims during the cooldown');
assert.match(server, /const mobile = String\(req\.authedMobile \|\| ""\)\.trim\(\)/, 'claim identity is resolved from the authenticated session');
assert.match(server, /user\.diamonds = clampDiamondBalance\(id, balance \+ reward, "daily-diamond-reward"\)/, 'server safely credits the authoritative diamond wallet');
assert.match(server, /dailyDiamondRewardHistory\.push/, 'claim history is persisted');
assert.match(server, /logTransaction\(id, "diamonds", reward, "daily-diamond-reward"\)/, 'reward credit is recorded in the wallet transaction history');
assert.match(app, /btn-daily-task-popup-claim/, 'popup claim button is wired to the server claim endpoint');
console.log('Daily diamond reward UI/API contract: PASS');
