const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const server = fs.readFileSync(path.join(root, 'server.js'), 'utf8');
const adminHtml = fs.readFileSync(path.join(root, 'admin/index.html'), 'utf8');
const adminApp = fs.readFileSync(path.join(root, 'admin/app.js'), 'utf8');
const app = fs.readFileSync(path.join(root, 'public/app.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8');
const payments = fs.readFileSync(path.join(root, 'payments/index.js'), 'utf8');
assert.match(server, /onlineRechargeAllowedForUser\(user\)[\s\S]*?user\.country[\s\S]*?=== "IN"/, 'online recharge eligibility uses actual ISO country, India only');
assert.match(server, /online-recharge-india-only/, 'non-India manual-online recharge has a server-side rejection');
assert.match(payments, /const onlineRechargeAllowed = \(req\) =>/, 'automatic gateway has a country eligibility guard');
assert.match(payments, /userRecordFrom\(req\)\?\.country[\s\S]*?=== 'IN'/, 'automatic gateway eligibility uses India ISO country');
assert.match(payments, /online-recharge-india-only/, 'gateway orders are server-blocked for non-India accounts');
assert.match(server, /app\.get\("\/api\/admin\/godpower\/inquiry\/:userId"/, 'God Power full user inquiry endpoint exists');
assert.match(server, /walletTransactions:[\s\S]*?rechargeTransactions:[\s\S]*?ownedRooms/, 'inquiry returns wallet, recharge, and room ownership details');
assert.match(server, /"sms-block", "sms-unblock", "notifications-block", "notifications-unblock"/, 'God Power supports SMS and notification restriction actions');
assert.match(server, /smsBlockedUser && smsBlockedUser\.smsBlocked/, 'SMS/OTP send is blocked for restricted accounts');
assert.match(server, /recipientFound\.user\.notificationsBlocked/, 'system notifications respect notification blocks');
assert.match(adminHtml, /Full User Inquiry/, 'Control Panel has full inquiry UI');
assert.match(adminHtml, /Block SMS \/ OTP/, 'Control Panel exposes SMS/OTP blocking');
assert.match(adminHtml, /Block system notifications/, 'Control Panel exposes notification blocking');
assert.match(adminApp, /btn-godpower-inquiry[\s\S]*?api\(`\/api\/admin\/godpower\/inquiry/, 'Control Panel inquiry UI calls the inquiry API');
assert.match(server, /Math\.floor\(previousBasis \/ 10000\)/, 'room bonus converts basis points to whole diamonds at 2%');
assert.match(server, /Math\.floor\(owner\.roomGiftBonusBasisPoints \/ 10000\)/, 'room bonus pending balance uses correct 2% conversion');
assert.match(server, /accrueRoomGiftBonus\(rooms\[roomId\], gift\.price\)/, 'REST gift path accrues room-owner bonus');
assert.match(app, /offlineRechargeOnly/, 'non-India users receive offline-only recharge UI');
