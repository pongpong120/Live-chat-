'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const server = fs.readFileSync(path.join(root, 'games/classicSlotServer.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'public/games/classic-slot/index.html'), 'utf8');
const serverSymbolsText = (server.match(/const symbols=\[([\s\S]*?)\];const CH/) || [])[1];
const clientSymbolsText = (html.match(/const SYM=\[([\s\S]*?)\];\s*const CH/) || [])[1];
assert.ok(serverSymbolsText && clientSymbolsText, 'server and client symbol tables must exist');
const pairs = text => [...text.matchAll(/m\s*:\s*(\d+)\s*,\s*w\s*:\s*(\d+)/g)].map(m => [Number(m[1]), Number(m[2])]);
assert.deepStrictEqual(pairs(serverSymbolsText), pairs(clientSymbolsText), '7/Bell/Diamond/fruit multipliers and RNG weights must match on server and client');
assert.match(server, /const amount=Math\.round\(totalBet\*mult\)/, 'server per-line payout rounding must match client evaluation');
assert.match(server, /if\(seq\[0\]===seq\[1\]&&seq\[1\]===seq\[2\]\)/, 'three matching symbols pay the configured multiplier');
assert.match(server, /else if\(seq\[0\]===CH&&seq\[1\]===CH\)mult=TWO_CHERRY/, 'two leading cherries use the TWO_CHERRY payout');
assert.match(html, /const LINES=\[\[\[0,0\],\[1,0\],\[2,0\]\]/, 'client uses the same left-to-right paylines');
assert.match(server, /const lines=\[\[\[0,0\],\[1,0\],\[2,0\]\]/, 'server uses the same left-to-right paylines');
assert.match(server, /const TWO_CHERRY=\.4;/, 'server two-cherry multiplier');
assert.match(html, /TWO_CHERRY=0\.4/, 'client two-cherry multiplier must match server');
assert.match(server, /const calc=payout\(grid,bet\)/, 'payout must be multiplier x TOTAL bet (not per-line bet)');
assert.match(html, /evaluate\(g,sc\?sc\.bet:total\(\)\)/, 'client evaluation must use TOTAL bet');
console.log('Classic Slot / Lucky Seven payout table, payline and rounding parity: PASS');
assert.match(server, /const calc=payout\(grid,bet\)/, 'payout must be multiplier x TOTAL bet, not per-line bet');
console.log('Classic Slot payout = multiplier x TOTAL BET: PASS');
